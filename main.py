# Строка документации модуля (docstring).
# Обычно пишется в кавычках """ в начале файла и описывает назначение всего файла.
"""Учебный проект для изучения Python и тестирования."""

# Типы (int, str, None и т.д.) в объявлениях функций — это подсказки для человека и для инструментов:
# они описывают, какие данные ожидаются и что возвращается. Python их не проверяет при запуске.

# Объявление функции add с аннотациями типов.
# def — ключевое слово для определения функции.
# add — имя функции.
# (a: int, b: int) — параметры: a и b, ожидается тип int (целое число).
# -> int — тип возвращаемого значения (функция вернёт целое число).
def add(a: int, b: int) -> int:
    """Складывает два числа."""  # Docstring функции — краткое описание для документации.
    return a + b  # return возвращает результат выражения a + b вызывающему коду.


# Функция main — традиционное имя для главной точки входа программы.
# -> None означает, что функция ничего не возвращает (только выполняет действия).
def main() -> None:
    """Точка входа в программу."""
    print("Проект успешно запущен!")  # print выводит текст в консоль.


# Запуск программы: вызываем main(), когда выполняют этот файл.
main()
